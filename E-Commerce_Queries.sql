WITH Product_Sales AS (
    SELECT
        p.Product_ID,
        p.Product_Name,
        p.Category,
        SUM(s.Quantity) AS Total_Quantity_Sold
    FROM product_dataset AS p
    INNER JOIN sales_dataset AS s
        ON p.Product_ID = s.Product_ID
    GROUP BY
        p.Product_ID,
        p.Product_Name,
        p.Category
),
Ranked_Products AS (
    SELECT
        Product_ID,
        Product_Name,
        Category,
        Total_Quantity_Sold,
        RANK() OVER (
            PARTITION BY Category
            ORDER BY Total_Quantity_Sold DESC
        ) AS Product_Rank
    FROM Product_Sales
)
SELECT
    Product_ID,
    Product_Name,
    Category,
    Total_Quantity_Sold
FROM Ranked_Products
WHERE Product_Rank = 1;

